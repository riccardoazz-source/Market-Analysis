import { DataPoint } from './types'

export async function fetchSP500Data(): Promise<DataPoint[]> {
  // On Vercel the server has internet access — try Yahoo Finance first
  if (process.env.NEXT_PUBLIC_USE_STATIC_DATA !== 'true') {
    try {
      const url = `https://query1.finance.yahoo.com/v8/finance/chart/%5EGSPC?interval=1mo&range=max&includeAdjustedClose=true`
      const res = await fetch(url, {
        headers: {
          'User-Agent':
            'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
            '(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36',
          Accept: 'application/json',
          'Accept-Language': 'en-US,en;q=0.9',
        },
        next: { revalidate: 86400 },
      })
      if (res.ok) {
        const json = await res.json()
        const result = json?.chart?.result?.[0]
        if (result) {
          const timestamps: number[] = result.timestamp ?? []
          const closes: (number | null)[] =
            result.indicators?.adjclose?.[0]?.adjclose ??
            result.indicators?.quote?.[0]?.close ??
            []
          const points: DataPoint[] = []
          for (let i = 0; i < timestamps.length; i++) {
            const close = closes[i]
            if (close != null && close > 0) {
              points.push({
                date: new Date(timestamps[i] * 1000).toISOString().split('T')[0],
                close: Math.round(close * 100) / 100,
                timestamp: timestamps[i] * 1000,
              })
            }
          }
          if (points.length > 100) return points
        }
      }
    } catch {
      // fall through to static data
    }
  }

  return getStaticData()
}

